            <p class="kicker">Category 2</p>
            <h2>Self-managed Space</h2>
            <p>A self-managed space flips the model: instead of a company running the house, the residents run it themselves. The members collectively decide who joins and who leaves, how the rent and chores are split, what the house rules are, and what kind of community they want to be. There is no operator margin, which usually makes self-managed living noticeably cheaper — and the community tends to be stronger, because everyone has a genuine stake in it.</p>
            <p>Self-managed spaces take many forms. A group of friends might rent a large villa for six months and interview new housemates together. A crew of founders might open a "popup" house for a season in Lisbon or Bali. A long-standing shared home might rotate residents over years while keeping its culture intact. What unites them is member-led governance: decisions are made by the people who actually live there.</p>
            <p>This category suits people who want more than a room — they want a say. If you enjoy shaping a community, voting on new housemates, and sharing responsibility for a home, self-managed living offers a depth of belonging that managed products rarely match.</p>

            <h3>Subcategories of Self-managed Spaces</h3>
            <ul class="subcats">
                <li><strong>Popup Space</strong> — a temporary self-managed house, apartment, villa, or hostel opened for a limited period, often a single season.</li>
                <li><strong>Temporary Community</strong> — a time-bound, member-led group formed around living together and sharing community life for a defined stretch.</li>
                <li><strong>Resident-led House</strong> — an ongoing shared home where current residents collectively manage membership and house decisions.</li>
                <li><strong>Fixed Dates</strong> — a self-managed space with clearly defined start and end dates, so everyone commits to the same window.</li>
            </ul>
            <a class="cta" href="/spaces/self-managed">Browse Self-managed spaces</a>
        </section>

        <section id="shared-housing">
            <p class="kicker">Category 3</p>
            <h2>Shared Housing</h2>
            <p>Shared housing is the oldest and most familiar form of living together: roommates sharing a flat or a house, each renting a room and splitting the kitchen, bathroom, and bills. There is usually no operator and no formal community program — just people sharing a home, whether they found each other through friends, classifieds, or a platform like this one.</p>
            <p>Compared with coliving, shared housing is typically cheaper and more flexible, but it also asks more of you: furnishing may be minimal, utilities are often in someone's name, and the social life is whatever the housemates make of it. Many great friendships (and some legendary houses) have come out of an ordinary flatshare — the difference between a place to sleep and a home usually comes down to the people.</p>
            <p>It is the natural choice for anyone on a budget, people new to a city testing a neighborhood before committing, or anyone who prefers a small household of two to five people over a larger community.</p>

            <h3>Subcategories of Shared Housing</h3>
            <ul class="subcats">
                <li><strong>Flat / Apartment</strong> — roommates sharing a single apartment unit, the classic city flatshare.</li>
                <li><strong>House / Villa</strong> — a whole house or villa shared by its residents, usually with more space and a garden or terrace.</li>
                <li><strong>Private Room</strong> — your own bedroom within a shared home; kitchen and bathroom are typically shared.</li>
                <li><strong>Shared Room</strong> — a shared bedroom arrangement with multiple beds in one room, the most affordable option.</li>
            </ul>
            <a class="cta" href="/spaces/shared-housing">Browse Shared Housing</a>
        </section>

        <section id="student-housing">
            <p class="kicker">Category 4</p>
            <h2>Student Housing</h2>
            <p>Student housing covers homes built around academic life: university dormitories, purpose-built student residences, and shared apartments aimed at students. The rhythm of these places follows the academic calendar — leases align with semesters, communities reset each year, and the location is chosen for proximity to campus, libraries, and student life.</p>
            <p>The appeal is simplicity and instant community. Residences typically come furnished with utilities included, contracts are designed for students (no lengthy employment checks), and you are surrounded by people in the same stage of life. For international students especially, arranged student housing removes the hardest part of moving abroad: finding a trustworthy home in a country you have never lived in.</p>
            <p>Examples include an on-campus dormitory with meal plans, a private student residence with study rooms and a cinema lounge, or a flat shared by exchange students for one Erasmus semester.</p>

            <h3>Subcategories of Student Housing</h3>
            <ul class="subcats">
                <li><strong>University Residence</strong> — dorms and residences managed by the university, often on or near campus.</li>
                <li><strong>Private Student Housing</strong> — student-focused housing run by private operators, usually with more amenities than a dorm.</li>
                <li><strong>Exchange / Erasmus</strong> — housing commonly used by exchange and Erasmus students, matched to semester dates.</li>
                <li><strong>Researcher / PhD</strong> — housing aimed at researchers, PhD candidates, and longer academic stays.</li>
            </ul>
            <a class="cta" href="/spaces/student-housing">Browse Student Housing</a>
        </section>

        <section id="digital-nomad">
            <p class="kicker">Category 5</p>
            <h2>Digital Nomad Coliving</h2>
            <p>Digital nomad coliving is designed for people who work online and move often. The essentials are non-negotiable: fast, reliable internet; proper workspaces with desks, monitors, and calls-friendly corners; and flexible stays measured in weeks or months rather than years. Around that core, each house builds its own personality — some feel like focused coworking retreats, others like a traveling friend group with laptops.</p>
            <p>What separates nomad coliving from a hostel or an Airbnb is the community of peers. Everyone in the house understands remote work: quiet hours during calls, coworking sessions during the day, and shared dinners, surf trips, or city explorations after. For remote workers tired of working alone in rented apartments, this category solves both loneliness and logistics in one move.</p>
            <p>Typical examples: a villa in Tenerife or Bali with a coworking room and weekly community dinners, a mountain chalet hosting a month-long "workation" season, or a founder-focused house where residents build startups side by side.</p>

            <h3>Subcategories of Digital Nomad Coliving</h3>
            <ul class="subcats">
                <li><strong>Work-first</strong> — optimized for focused remote work: coworking rooms, ergonomic desks, and rock-solid internet.</li>
                <li><strong>Community-first</strong> — designed around social connection, shared meals, events, and community routines.</li>
                <li><strong>Builder house</strong> — startup, founder, and builder-focused communities where residents collaborate on projects.</li>
                <li><strong>Travel-first</strong> — oriented toward experiences, exploration, and location-based activities like surfing or skiing.</li>
            </ul>
            <a class="cta" href="/spaces/digital-nomad">Browse Digital Nomad Coliving</a>
        </section>

        <section id="cohousing">
            <p class="kicker">Category 6</p>
            <h2>Cohousing / Communal Living</h2>
            <p>Cohousing and communal living are the long-horizon end of the shared living spectrum: intentional communities where residents don't just share a building, they co-create a way of life. In formal cohousing, households own or rent private homes clustered around shared facilities — a common house, gardens, workshops — and govern the community together. In communes and intentional communities, sharing often goes deeper, extending to meals, resources, income, or a common mission.</p>
            <p>These communities are usually built to last decades, not months. Residents commit to participation: cooking rotas, community meetings, consensus decision-making, and shared upkeep of the land or buildings. In return they get something rare — genuine, multigenerational neighborhood life, where children grow up with dozens of trusted adults around and nobody ages in isolation.</p>
            <p>Examples include a purpose-built cohousing neighborhood of twenty households with a shared dining hall, a rural eco-village growing its own food, or an urban commune organized around a shared social mission.</p>

            <h3>Subcategories of Cohousing / Communal Living</h3>
            <ul class="subcats">
                <li><strong>Cohousing (Formal)</strong> — resident-led communities with intentional design, shared governance, and common facilities alongside private homes.</li>
                <li><strong>Commune (Informal)</strong> — informal communal living with deeply shared resources and collaborative daily routines.</li>
                <li><strong>Eco Community</strong> — communities centered on sustainability: permaculture, natural building, and low-impact living.</li>
                <li><strong>Intentional Community</strong> — groups formed around shared values, a lifestyle, or a common mission.</li>
            </ul>
            <a class="cta" href="/spaces/cohousing">Browse Cohousing &amp; Communal Living</a>
        </section>

        <section id="senior-coliving">
            <p class="kicker">Category 7</p>
            <h2>Senior Coliving</h2>
            <p>Senior coliving applies the best ideas of shared living to later life: private, comfortable homes combined with real community, so that growing older doesn't mean growing lonely. Residents keep their independence — their own room or apartment, their own routines — while sharing meals, activities, gardens, and mutual support with neighbors in the same stage of life.</p>
            <p>The category spans a wide range of support levels. Independent living communities are essentially social housing clusters for active older adults. Assisted living adds on-site care services when daily help is needed. Intergenerational models deliberately mix ages — students or young professionals living alongside seniors, trading company and small favors for affordable rent — an arrangement that consistently proves good for everyone involved.</p>
            <p>For older adults, downsizing into senior coliving often means lower costs, less home maintenance, built-in companionship, and peace of mind for family members — without giving up autonomy.</p>

            <h3>Subcategories of Senior Coliving</h3>
            <ul class="subcats">
                <li><strong>Independent Living</strong> — independent shared living with light services and strong community support.</li>
                <li><strong>Assisted Living</strong> — shared living with care and assistance services available on site.</li>
                <li><strong>Intergenerational</strong> — communities that intentionally mix age groups and encourage connection between generations.</li>
                <li><strong>55+ Community</strong> — age-restricted communities designed for residents aged 55 and older.</li>
            </ul>
            <a class="cta" href="/spaces/senior-coliving">Browse Senior Coliving</a>
        </section>

        <section id="short-term">
            <p class="kicker">Category 8</p>
            <h2>Short-Term Coliving</h2>
            <p>Short-term coliving is community living with a deadline — and that deadline is the point. Whether it's a two-week creative retreat, a winter house in a ski town, or a month-long pop-up in a city none of the participants have lived in before, the fixed timeframe concentrates the experience. Everyone arrives knowing the window is short, so connections form fast and the house develops its own culture within days.</p>
            <p>This category is ideal for testing coliving before committing to it long-term, for sabbaticals and workations, or for joining a focused burst of collective energy: writing retreats, startup sprints, artist residencies, or seasonal surf and snow houses. Many people alternate — living conventionally most of the year and joining one or two short-term houses to recharge their social battery.</p>
            <p>Examples: a summer house on a Greek island running June through September, a ten-day retreat built around a wellness program, or a pop-up coliving experiment in a converted hotel.</p>

            <h3>Subcategories of Short-Term Coliving</h3>
            <ul class="subcats">
                <li><strong>Seasonal</strong> — houses that operate around a season, like summer villas or winter ski chalets.</li>
                <li><strong>Retreat-Based</strong> — short stays centered on a retreat, program, or shared experience.</li>
                <li><strong>Pop-Up</strong> — temporary houses that open for a limited time, often in unexpected places.</li>
                <li><strong>Project-Based</strong> — temporary living built around a project, residency, or focused collaboration.</li>
            </ul>
            <a class="cta" href="/spaces/short-term">Browse Short-Term Coliving</a>
        </section>

        <section id="how-to-choose">
            <h2>How to Choose the Right Category</h2>
            <p>If the categories blur together, three questions will point you to the right one:</p>
            <p><strong>1. Who runs the home?</strong> If you want convenience and a professional point of contact, choose <a href="/spaces/managed-coliving">managed coliving</a> or <a href="/spaces/student-housing">student housing</a>. If you want a say in who you live with and how the house works, look at <a href="/spaces/self-managed">self-managed spaces</a>, <a href="/spaces/shared-housing">shared housing</a>, or <a href="/spaces/cohousing">cohousing</a>.</p>
            <p><strong>2. How long are you staying?</strong> Weeks to a few months points to <a href="/spaces/short-term">short-term coliving</a> or <a href="/spaces/digital-nomad">nomad houses</a>. A year or more opens up managed coliving, shared housing, and student residences. Thinking in decades? That's cohousing territory.</p>
            <p><strong>3. What stage of life are you in?</strong> Students have a category built for their calendar. Remote workers have houses built around their laptops. Older adults have communities built around comfort and connection. Everyone else can mix and match.</p>
            <div class="compare-note">
                <strong>Rule of thumb:</strong> managed coliving buys you convenience, self-managed and shared housing buy you affordability and ownership of the community, and specialized categories (student, nomad, senior, short-term) buy you a house full of people whose lives currently look like yours.
            </div>
        </section>

        <section id="faq" class="faq">
            <h2>Frequently Asked Questions</h2>

            <h3>What is the difference between coliving and a flatshare?</h3>
            <p>A flatshare is usually a group of roommates renting a home and organizing everything themselves. Coliving is designed for community from the start: furnished spaces, bills included, common areas planned for socializing, and an operator or resident community that curates who moves in.</p>

            <h3>What does managed coliving mean?</h3>
            <p>Managed coliving is run by a professional operator. You rent a private room, studio, or apartment inside a shared building, and the operator handles cleaning, maintenance, utilities, and often community events. It's the most convenient, hands-off form of shared living.</p>

            <h3>What is a self-managed coliving space?</h3>
            <p>A self-managed space is run by its residents rather than a company. Members collectively decide who joins, how costs are split, and how the house operates. It usually costs less than managed coliving and gives residents real ownership of the community.</p>

            <h3>Is coliving cheaper than renting an apartment?</h3>
            <p>Often, yes — especially once you count everything in. A room in shared housing or a self-managed space is almost always cheaper than a solo apartment. Managed coliving can match a studio's price, but rent usually includes furniture, utilities, internet, and cleaning, so the all-in cost is frequently lower.</p>

            <h3>Which type of coliving is best for digital nomads?</h3>
            <p><a href="/spaces/digital-nomad">Digital nomad coliving</a> — it's built for remote work with fast internet, real workspaces, flexible stays, and a community of people who also work online. Pick work-first houses for productivity, community-first or travel-first houses for social life and exploring.</p>
        </section>

